/**
 * Integration tests that need a *real* server and *real* network conditions,
 * but no internet: every fixture is generated locally with FFmpeg and served
 * from 127.0.0.1.
 *
 *   npm run build && npm start      # terminal 1
 *   npm run test:e2e:integration    # terminal 2
 *
 * What it covers (the two paths that could not be signed off by hand-waving):
 *
 *   1. Playlist path — four entries, three downloadable, one broken. The job
 *      must finish with 3 files and report exactly one missing entry; the
 *      "retry missing" action must then be accepted (and record its attempt).
 *   2. HLS path — a master playlist behind a Referer+Cookie guard. Plain
 *      requests must fail with a 403 explanation; with the session headers the
 *      download must succeed, send the headers to every segment request, and
 *      honour the requested quality (720p) instead of the best variant (1080p).
 *
 * BASE_URL points at the app; the fixtures pick free ports themselves.
 */
import { execFileSync, spawn, type ChildProcess } from "node:child_process";
import { existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { tmpdir } from "node:os";
import path from "node:path";

const BASE = process.env.BASE_URL ?? "http://127.0.0.1:3000";
const WORK = process.env.E2E_FIXTURE_DIR ?? path.join(tmpdir(), "bh-e2e-fixtures");
const DEADLINE_MS = Number(process.env.E2E_DEADLINE_MS ?? 240_000);
const startedAt = Date.now();
const FFPROBE = process.env.FFPROBE_PATH ?? "ffprobe";
const REFERER = "https://player.example/";
const COOKIE_VALUE = "secret-pass";

type Check = { name: string; ok: boolean; detail?: string };
const checks: Check[] = [];
const cleanups: (() => void | Promise<void>)[] = [];

function record(name: string, ok: boolean, detail?: string) {
  checks.push({ name, ok, detail });
  console.log(`${ok ? "✓" : "✗"} ${name}${detail ? ` — ${detail}` : ""}`);
}

async function json<T>(route: string, init?: RequestInit): Promise<{ status: number; body: T }> {
  const res = await fetch(`${BASE}${route}`, {
    ...init,
    headers: { "Content-Type": "application/json", ...(init?.headers ?? {}) },
  });
  const body = (await res.json().catch(() => ({}))) as T;
  return { status: res.status, body };
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

