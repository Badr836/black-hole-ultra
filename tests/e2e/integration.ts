function ffmpeg(args: string[]) {
  execFileSync(process.env.FFMPEG_PATH ?? "ffmpeg", ["-y", "-loglevel", "error", ...args], { stdio: "pipe" });
}

/** Three tiny real MP4s + one HTML page that lists four of them (the fourth 404s). */
function buildPlaylistFixture(dir: string) {
  const videoDir = path.join(dir, "video");
  mkdirSync(videoDir, { recursive: true });
  for (const n of [1, 2, 3]) {
    const file = path.join(videoDir, `${n}.mp4`);
    if (existsSync(file) && readFileSync(file).length > 1_000) continue;
    ffmpeg([
      "-f", "lavfi", "-i", "testsrc2=size=320x240:rate=15",
      "-f", "lavfi", "-i", `sine=frequency=${400 + n * 100}`,
      "-t", "2", "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
      "-c:a", "aac", "-b:a", "64k", file,
    ]);
  }
  return videoDir;
}

/** A two-variant HLS stream (1080p / 720p) plus the page-less master playlist. */
function buildHlsFixture(dir: string) {
  const src = path.join(dir, "hls");
  const master = path.join(src, "master.m3u8");
  if (existsSync(master)) return src;
  mkdirSync(src, { recursive: true });
  for (const height of [1080, 720]) {
    const width = height === 1080 ? 1920 : 1280;
    const bitrate = height === 1080 ? "3000k" : "1200k";
    const out = path.join(src, String(height));
    mkdirSync(out, { recursive: true });
    ffmpeg([
      "-f", "lavfi", "-i", `testsrc2=size=${width}x${height}:rate=25`,
      "-f", "lavfi", "-i", `sine=frequency=${height * 3}`,
      "-t", "8", "-c:v", "libx264", "-preset", "ultrafast", "-b:v", bitrate, "-g", "50", "-pix_fmt", "yuv420p",
      "-c:a", "aac", "-b:a", "96k", "-f", "hls", "-hls_time", "2", "-hls_playlist_type", "vod",
      "-hls_segment_filename", path.join(out, "seg%d.ts"), path.join(out, "index.m3u8"),
    ]);
  }
  writeFileSync(
    master,
    [
      "#EXTM3U",
      "#EXT-X-VERSION:3",
      '#EXT-X-STREAM-INF:BANDWIDTH=3200000,RESOLUTION=1920x1080,CODECS="avc1.42c02a,mp4a.40.2"',
      "1080/index.m3u8",
      '#EXT-X-STREAM-INF:BANDWIDTH=1400000,RESOLUTION=1280x720,CODECS="avc1.42c02a,mp4a.40.2"',
      "720/index.m3u8",
      "",
    ].join("\n"),
  );
  return src;
}

/**
 * A master playlist with one 720p video and **two audio languages** (Arabic /
 * English), generated by FFmpeg's `var_stream_map`. Used to prove that
 * `--select-audio lang=…` picks the requested language (the offline analogue of
 * a broadcaster offering dubs).
 */
function buildMultiAudioFixture(dir: string) {
  const src = path.join(dir, "multi-audio");
  const master = path.join(src, "master.m3u8");
  if (existsSync(master)) return src;
  mkdirSync(src, { recursive: true });
  ffmpeg([
    "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=25",
    "-f", "lavfi", "-i", "sine=frequency=600",
    "-f", "lavfi", "-i", "sine=frequency=900",
    "-t", "6",
    "-map", "0:v", "-map", "1:a", "-map", "2:a",
    "-c:v", "libx264", "-preset", "ultrafast", "-g", "50", "-pix_fmt", "yuv420p",
    "-c:a", "aac", "-b:a", "64k",
    "-f", "hls", "-hls_time", "2", "-hls_playlist_type", "vod",
    "-var_stream_map", "v:0,agroup:aud a:0,agroup:aud,language:Arabic,name:Arabic a:1,agroup:aud,language:English,name:English",
    "-master_pl_name", "master.m3u8",
    "-hls_segment_filename", path.join(src, "%v_%d.ts"),
    path.join(src, "%v.m3u8"),
  ]);
  return src;
}

/** Static origin for the playlist fixture; the page is generated with the port baked in. */
function startPlaylistOrigin(videoDir: string, port: number, logFile: string) {
  const page = (origin: string) => {
    const rows = [1, 2, 3, 4]
      .map(
        (n) =>
          `<video controls src="${origin}/video/${n}.mp4" title="episode-${n}"></video>`,
      )
      .join("\n");
    return `<!doctype html><html><head><title>Local mini series</title></head><body>\n${rows}\n</body></html>\n`;
  };

  const server = createServer((req, res) => {
    const url = new URL(req.url ?? "/", `http://127.0.0.1:${port}`);
    if (url.pathname === "/list.html") {
      const body = page(`http://127.0.0.1:${port}`);
      res.writeHead(200, { "content-type": "text/html; charset=utf-8", "content-length": Buffer.byteLength(body) });
      res.end(body);
      return;
    }
    const match = /^\/video\/([1-3])\.mp4$/.exec(url.pathname);
    if (!match) {
      res.writeHead(404, { "content-type": "text/plain" });
      res.end("not found");
      return;
    }
    const body = readFileSync(path.join(videoDir, `${match[1]}.mp4`));
    res.writeHead(200, { "content-type": "video/mp4", "content-length": body.length, "accept-ranges": "bytes" });
    res.end(body);
  });
  server.listen(port, "127.0.0.1");
  return server;
}

async function freePort(start = 8911): Promise<number> {
  for (let port = start; port < start + 200; port += 1) {
    const free = await new Promise<boolean>((resolve) => {
      const probe = createServer();
      probe.once("error", () => resolve(false));
      probe.once("listening", () => probe.close(() => resolve(true)));
      probe.listen(port, "127.0.0.1");
    });
    if (free) return port;
  }
  throw new Error("no free port");
}

// ------------------------------------------------------------------ helpers ---

type Row = {
  id: number;
  status: string;
  error: string | null;
  filePath: string | null;
  files: string[] | null;
  completedEntries: number | null;
  totalBytes: number | null;
  metadata: Record<string, unknown> | null;
};

async function waitFor(id: number, timeoutMs = 120_000): Promise<Row> {
  const until = Date.now() + timeoutMs;
  let row = (await json<Row>(`/api/downloads/${id}`)).body;
  while (Date.now() < until) {
    if (["completed", "failed", "cancelled"].includes(row.status)) return row;
    await sleep(1000);
    row = (await json<Row>(`/api/downloads/${id}`)).body;
  }
  return row;
}

function probeHeight(file: string): number | null {
  try {
    const out = execFileSync(
      FFPROBE,
      ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=height", "-of", "csv=p=0", file],
      { encoding: "utf8" },
    ).trim();
    const value = Number(out.split("\n")[0]);
    return Number.isFinite(value) ? value : null;
  } catch {
    return null;
  }
}

function probeStreams(file: string): string {
  try {
    const out = execFileSync(
      FFPROBE,
      ["-v", "error", "-show_entries", "stream=codec_type", "-of", "csv=p=0", file],
      { encoding: "utf8" },
    ).trim();
    return out.split("\n").filter(Boolean).join("+");
  } catch {
    return "";
  }
}

function ping(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    fetch(`http://127.0.0.1:${port}/master.m3u8`)
      .then(() => resolve(true))
      .catch(() => resolve(false));
  });
}

type GuardOptions = { referer: string; cookie?: string; logFile: string };

/** Start tests/fixtures/protected-hls-server.mjs and wait until it answers. */
async function startGuardedOrigin(dir: string, options: GuardOptions): Promise<number> {
  const port = await freePort(8941);
  writeFileSync(options.logFile, "");
  const child = spawn(
    process.execPath,
    [
      path.join(process.cwd(), "tests/fixtures/protected-hls-server.mjs"),
      dir,
      String(port),
      options.referer,
      options.cookie ?? "",
    ],
    {
      env: { ...process.env, HLS_LOG: options.logFile },
      stdio: ["ignore", openSync(path.join(WORK, "hls-server.log"), "a"), openSync(path.join(WORK, "hls-server.log"), "a")],
    },
  );
  cleanups.push(() => {
    child.kill("SIGTERM");
  });
  for (let i = 0; i < 80; i += 1) {
    if (await ping(port)) return port;
    await sleep(150);
  }
  return port;
}

