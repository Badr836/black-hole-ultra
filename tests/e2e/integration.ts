async function main() {
  const health = await json<{ ok: boolean; db: { schemaVersion: number } }>("/api/health");
  if (health.status !== 200) {
    console.error(`لا يوجد خادم على ${BASE} — شغّل npm start أولاً.`);
    return finish(1);
  }
  record("GET /api/health", health.body.ok === true, `schema v${health.body.db?.schemaVersion}`);

  const system = await json<{
    ytdlp: { ok: boolean };
    ffmpeg: { ok: boolean };
    nm3u8dl?: { ok: boolean };
  }>("/api/system");
  if (!system.body.ytdlp.ok || !system.body.ffmpeg.ok) {
    console.log("\n[skip] yt-dlp/ffmpeg غير متاحين — لا يمكن تشغيل الاختبارات التكاملية.");
    return finish(0);
  }
  if (!system.body.nm3u8dl?.ok) {
    console.log("\n[skip] N_m3u8DL-RE غير مثبّت — تخطّي مسار HLS.");
  }

  // Keep the user's settings intact across runs.
  const original = (await json<Record<string, unknown>>("/api/settings")).body;
  cleanups.push(async () => {
    await json("/api/settings", {
      method: "PUT",
      body: JSON.stringify({
        hlsHeaders: original.hlsHeaders ?? null,
        hlsUseCookies: original.hlsUseCookies ?? true,
        cookiesPath: original.cookiesPath ?? null,
        providerPreference: original.providerPreference ?? "auto",
        maxRetries: original.maxRetries ?? 3,
        maxConcurrent: original.maxConcurrent ?? 3,
        hlsAutoHeaders: original.hlsAutoHeaders ?? true,
        hlsAudioLang: original.hlsAudioLang ?? null,
        hlsVideoRange: original.hlsVideoRange ?? null,
        hlsCodecs: original.hlsCodecs ?? null,
      }),
    });
  });

  mkdirSync(WORK, { recursive: true });

  // ======================================================= 1) playlist path ===
  const videoDir = buildPlaylistFixture(WORK);
  const playlistPort = await freePort(8911);
  const playlistLog = path.join(WORK, "playlist-requests.log");
  writeFileSync(playlistLog, "");
  const playlistOrigin = startPlaylistOrigin(videoDir, playlistPort, playlistLog);
  cleanups.push(() => new Promise<void>((resolve) => playlistOrigin.close(() => resolve())));

  // Wait for the origin to answer before queueing a job.
  for (let i = 0; i < 40; i += 1) {
    const res = await fetch(`http://127.0.0.1:${playlistPort}/list.html`).catch(() => null);
    if (res?.ok) break;
    await sleep(100);
  }

  await json("/api/settings", { method: "PUT", body: JSON.stringify({ providerPreference: "auto", maxRetries: 1, maxConcurrent: 3 }) });

  const playlistUrl = `http://127.0.0.1:${playlistPort}/list.html`;
  const created = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({
      url: playlistUrl,
      title: "e2e-playlist",
      kind: "video",
      quality: "best",
      container: "mp4",
      playlist: true,
    }),
  });
  record("playlist job accepted", created.status === 201 && typeof created.body.id === "number", `id=${created.body.id}`);

  const playlistId = created.body.id;
  const done = await waitFor(playlistId);
  const files = done.files ?? [];
  const missing = (done.metadata?.missingItems as { index: number; reason: string }[] | undefined) ?? [];

  record("playlist reached a terminal state", ["completed", "failed"].includes(done.status), `status=${done.status}`);
  record("playlist kept the three good items", files.length === 3, `${files.length} file(s) · ${done.completedEntries ?? "?"} entry count`);
  record("playlist reported exactly one missing item", missing.length === 1, missing.map((m) => `#${m.index}: ${m.reason}`).join(" | ") || "لا شيء");
  record("missing item is the fourth entry", missing[0]?.index === 4, String(missing[0]?.index));
  record(
    "the three produced files are real media",
    files.length === 3 && files.every((file) => probeHeight(file) === 240),
    files.map((file) => `${path.basename(file)}=${probeHeight(file)}`).join(", "),
  );

  // Retry-incomplete must be accepted and must record its attempt.
  const retry = await json<{ ok?: boolean; error?: string }>(`/api/downloads/${playlistId}`, {
    method: "POST",
    body: JSON.stringify({ action: "retry-missing" }),
  });
  record("retry-missing is accepted for the incomplete playlist", retry.status === 200 && retry.body.ok === true, retry.body.error);

  const retried = await waitFor(playlistId);
  const retryCount = Number(retried.metadata?.incompleteRetry ?? 0);
  record("retry-missing recorded its attempt", retryCount === 1, `incompleteRetry=${retryCount}`);
  record(
    "the still-broken item is reported again (nothing silently lost)",
    ((retried.metadata?.missingItems as unknown[] | undefined) ?? []).length === 1,
    `status=${retried.status}`,
  );

  await fetch(`${BASE}/api/downloads/${playlistId}?deleteFile=1`, { method: "DELETE" });

  // ============================================================ 2) HLS path ===
  if (!system.body.nm3u8dl?.ok) {
    return finish(checks.some((c) => !c.ok) ? 1 : 0);
  }

  const hlsSrc = buildHlsFixture(WORK);
  const hlsLog = path.join(WORK, "hls-requests.log");
  const hlsPort = await startGuardedOrigin(hlsSrc, { referer: REFERER, cookie: COOKIE_VALUE, logFile: hlsLog });

  const cookiesFile = path.join(WORK, "cookies.txt");
  writeFileSync(
    cookiesFile,
    `# Netscape HTTP Cookie File\n127.0.0.1\tFALSE\t/\tFALSE\t0\tsession\t${COOKIE_VALUE}\n`,
  );
  const hlsUrl = `http://127.0.0.1:${hlsPort}/master.m3u8`;

  // (a) without session headers the guarded origin must be refused.
  await json("/api/settings", {
    method: "PUT",
    body: JSON.stringify({ providerPreference: "nm3u8dl", maxRetries: 0, hlsHeaders: "", hlsUseCookies: false, cookiesPath: null }),
  });
  const denied = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({ url: hlsUrl, title: "e2e-hls-denied", kind: "video", quality: "720", container: "mp4" }),
  });
  const deniedRow = await waitFor(denied.body.id);
  record(
    "protected HLS fails without Referer/Cookie (403 surfaced in Arabic)",
    deniedRow.status === "failed" && /403/.test(deniedRow.error ?? ""),
    `${deniedRow.status} · ${(deniedRow.error ?? "").slice(0, 80)}`,
  );
  await fetch(`${BASE}/api/downloads/${denied.body.id}?deleteFile=1`, { method: "DELETE" });

  // (b) with Referer + Cookie it must download, and pick the requested quality.
  const withHeaders = await json<Record<string, unknown>>("/api/settings", {
    method: "PUT",
    body: JSON.stringify({
      hlsHeaders: `Referer: ${REFERER}`,
      hlsUseCookies: true,
      cookiesPath: cookiesFile,
      providerPreference: "nm3u8dl",
      maxRetries: 0,
    }),
  });
  record(
    "settings accept HLS headers + cookies",
    withHeaders.status === 200 && withHeaders.body.hlsHeaders === `Referer: ${REFERER}` && withHeaders.body.cookiesPath === cookiesFile,
    `rejected=${JSON.stringify(withHeaders.body.rejected ?? [])}`,
  );

  writeFileSync(hlsLog, "");
  const allowed = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({ url: hlsUrl, title: "e2e-hls-720", kind: "video", quality: "720", container: "mp4" }),
  });
  const allowedRow = await waitFor(allowed.body.id);
  record("protected HLS completes with session headers", allowedRow.status === "completed", `${allowedRow.status} · ${(allowedRow.error ?? "").slice(0, 80)}`);
  record("downloaded file is 720p (requested quality, not the best variant)", allowedRow.filePath ? probeHeight(allowedRow.filePath) === 720 : false, allowedRow.filePath ? `${probeHeight(allowedRow.filePath)}p` : "no file");

  const hlsLogText = existsSync(hlsLog) ? readFileSync(hlsLog, "utf8") : "";
  const allowedLines = hlsLogText.split("\n").filter((line) => line.includes("ALLOW"));
  const deniedLines = hlsLogText.split("\n").filter((line) => line.includes("DENY"));
  record("origin received Referer + Cookie on every request", allowedLines.length > 0 && deniedLines.length === 0, `${allowedLines.length} allow · ${deniedLines.length} deny`);
  record("all requests carried the current session cookie", allowedLines.every((line) => line.includes(`session=${COOKIE_VALUE}`)));
  record(
    "the 720p variant was selected",
    allowedLines.some((line) => line.includes("/720/index.m3u8")) && !allowedLines.some((line) => line.includes("/1080/index.m3u8")),
    allowedLines.map((line) => line.split("\t")[1]).filter(Boolean).slice(0, 4).join(", "),
  );

  // (c) quality "best" must keep the tool's own best-pick (1080p here).
  writeFileSync(hlsLog, "");
  const best = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({ url: hlsUrl, title: "e2e-hls-best", kind: "video", quality: "best", container: "mp4" }),
  });
  const bestRow = await waitFor(best.body.id);
  record("best-quality HLS run completes", bestRow.status === "completed", bestRow.error ?? undefined);
  record("best quality picked the 1080p variant", bestRow.filePath ? probeHeight(bestRow.filePath) === 1080 : false, bestRow.filePath ? `${probeHeight(bestRow.filePath)}p` : "no file");

  await fetch(`${BASE}/api/downloads/${allowed.body.id}?deleteFile=1`, { method: "DELETE" });
  await fetch(`${BASE}/api/downloads/${best.body.id}?deleteFile=1`, { method: "DELETE" });

  // ============================== 3) auto-derived headers + audio language ===
  // (a) The guard accepts any same-origin Referer. The user pasted *nothing*:
  //     the app must derive `Referer: <manifest origin>` and succeed.
  const sameOriginLog = path.join(WORK, "hls-same-origin.log");
  const sameOriginSrc = buildHlsFixture(WORK);
  const sameOriginPort = await startGuardedOrigin(sameOriginSrc, {
    referer: "same-origin",
    logFile: sameOriginLog,
  });
  await json("/api/settings", {
    method: "PUT",
    body: JSON.stringify({ hlsHeaders: "", hlsUseCookies: false, cookiesPath: null, hlsAutoHeaders: true, maxRetries: 0 }),
  });

  const auto = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({
      url: `http://127.0.0.1:${sameOriginPort}/master.m3u8`,
      title: "e2e-hls-auto",
      kind: "video",
      quality: "720",
      container: "mp4",
    }),
  });
  const autoRow = await waitFor(auto.body.id);
  const autoLog = existsSync(sameOriginLog) ? readFileSync(sameOriginLog, "utf8") : "";
  record(
    "HLS works with zero pasted headers (Referer derived from the stream origin)",
    autoRow.status === "completed",
    `${autoRow.status} · ${(autoRow.error ?? "").slice(0, 70)}`,
  );
  record(
    "derived Referer was actually sent to the origin",
    autoLog.split("\n").some((line) => line.includes(`referer="http://127.0.0.1:${sameOriginPort}/"`) && line.includes("ALLOW")),
    `${autoLog.split("\n").filter((line) => line.includes("ALLOW")).length} allow`,
  );
  record(
    "the job records which header candidate won",
    ["origin", "page", "user"].includes(String(autoRow.metadata?.hlsHeadersUsed ?? "")),
    String(autoRow.metadata?.hlsHeadersUsed ?? "—"),
  );
  await fetch(`${BASE}/api/downloads/${auto.body.id}?deleteFile=1`, { method: "DELETE" });

  // (b) A page URL supplied per download must be used as the Referer.
  const pageLog = path.join(WORK, "hls-page-referer.log");
  const pagePort = await startGuardedOrigin(sameOriginSrc, { referer: REFERER, logFile: pageLog });
  const fromPage = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({
      url: `http://127.0.0.1:${pagePort}/master.m3u8`,
      pageUrl: REFERER,
      title: "e2e-hls-page-referer",
      kind: "video",
      quality: "720",
      container: "mp4",
    }),
  });
  const pageRow = await waitFor(fromPage.body.id);
  const pageLogText = existsSync(pageLog) ? readFileSync(pageLog, "utf8") : "";
  record(
    "a per-download page URL becomes the Referer",
    pageRow.status === "completed" && pageRow.metadata?.hlsHeadersUsed === "page",
    `${pageRow.status} · candidate=${String(pageRow.metadata?.hlsHeadersUsed ?? "—")}`,
  );
  record(
    "the watch-page Referer reached the origin",
    pageLogText.split("\n").some((line) => line.includes(`referer="${REFERER}"`)),
    `${pageLogText.split("\n").filter((line) => line.includes("ALLOW")).length} allow`,
  );
  await fetch(`${BASE}/api/downloads/${fromPage.body.id}?deleteFile=1`, { method: "DELETE" });

  // (c) Multi-audio manifest: the requested language must be the one saved.
  const multiSrc = buildMultiAudioFixture(WORK);
  const multiLog = path.join(WORK, "hls-multi-audio.log");
  const multiPort = await startGuardedOrigin(multiSrc, { referer: "same-origin", logFile: multiLog });
  const inspect = await json<{
    ok?: boolean;
    variants?: { height: number | null }[];
    audio?: { language: string | null }[];
    suggestions?: { audioLanguages: (string | null)[] };
    headersUsed?: string | null;
    error?: string;
  }>("/api/hls/inspect", {
    method: "POST",
    body: JSON.stringify({ url: `http://127.0.0.1:${multiPort}/master.m3u8` }),
  });
  const languages = (inspect.body.audio ?? []).map((track) => track.language).filter(Boolean);
  record(
    "inspect reports the real variants (720p)",
    inspect.status === 200 && (inspect.body.variants ?? []).some((variant) => variant.height === 720),
    `${(inspect.body.variants ?? []).length} variant(s)`,
  );
  record(
    "inspect reports the audio languages available",
    languages.includes("Arabic") && languages.includes("English"),
    languages.join(", ") || inspect.body.error,
  );
  record("inspect worked without pasted headers", inspect.body.headersUsed === "origin", String(inspect.body.headersUsed));

  const arabic = await json<{ id: number }>("/api/downloads", {
    method: "POST",
    body: JSON.stringify({
      url: `http://127.0.0.1:${multiPort}/master.m3u8`,
      title: "e2e-hls-audio-ar",
      kind: "video",
      quality: "720",
      container: "mp4",
      hlsAudioLang: "Arabic",
    }),
  });
  const arabicRow = await waitFor(arabic.body.id);
  const multiLogText = existsSync(multiLog) ? readFileSync(multiLog, "utf8") : "";
  record(
    "audio-language selection completes",
    arabicRow.status === "completed",
    `${arabicRow.status} · ${(arabicRow.error ?? "").slice(0, 70)}`,
  );
  const audioStreams = arabicRow.filePath ? probeStreams(arabicRow.filePath) : "";
  record(
    "the muxed file contains both video and audio",
    /video/.test(audioStreams) && /audio/.test(audioStreams),
    audioStreams || "no file",
  );
  record(
    "only the requested audio playlist was fetched",
    multiLogText.includes("/Arabic.m3u8") && !multiLogText.includes("/English.m3u8"),
    [...new Set(multiLogText.split("\n").map((line) => line.split("\t")[1]).filter(Boolean))]
      .filter((name) => name && name.endsWith(".m3u8"))
      .join(", "),
  );
  await fetch(`${BASE}/api/downloads/${arabic.body.id}?deleteFile=1`, { method: "DELETE" });

  return finish(checks.some((c) => !c.ok) ? 1 : 0);
}

async function cleanup() {
  for (const fn of cleanups.reverse()) {
    try {
      await fn();
    } catch {
      /* best effort */
    }
  }
  if (process.env.E2E_KEEP_FIXTURES !== "1") {
    rmSync(WORK, { recursive: true, force: true });
  }
}

function finish(code: number) {
  const failed = checks.filter((c) => !c.ok);
  console.log(`\n${checks.length - failed.length}/${checks.length} فحوص ناجحة · ${((Date.now() - startedAt) / 1000).toFixed(1)}s`);
  if (failed.length > 0) {
    console.log("فشل:");
    for (const f of failed) console.log(`  - ${f.name}${f.detail ? ` (${f.detail})` : ""}`);
  }
  cleanup().finally(() => process.exit(code));
  return undefined;
}

main().catch(async (error) => {
  console.error("integration crashed:", error);
  record("integration suite ran without crashing", false, error instanceof Error ? error.message : String(error));
  finish(1);
});
